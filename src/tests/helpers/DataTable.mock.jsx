// Versión simplificada de DataTable para probar las páginas sin depender del componente real.
export default function DataTable({ columns, rows, emptyText }) {
  if (!rows || rows.length === 0) return <p>{emptyText}</p>
  return (
    <table>
      <thead>
        <tr>
          {columns.map((c) => (
            <th key={c.key}>{c.label}</th>
          ))}
        </tr>
      </thead>
      <tbody>
        {rows.map((row, i) => (
          <tr key={i}>
            {columns.map((c) => (
              <td key={c.key}>{c.render ? c.render(row) : row[c.key]}</td>
            ))}
          </tr>
        ))}
      </tbody>
    </table>
  )
}
